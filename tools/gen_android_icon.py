#!/usr/bin/env python3
"""Generate the Android launcher icon from the desktop icon's geometry.

packaging/linux/tt2.svg is the project's own icon (a pearl letter ball with
a blocky "T" on a blue tile; no GameHouse art). Android 8+ draws launcher
icons as two layers the launcher masks into its own shape (circle,
squircle, ...), and Android 13+ adds a one-colour layer it tints with the
wallpaper colours when themed icons are on:

    background   the tile's blue gradient, full bleed (no gold rim: the
                 mask would cut it differently on every launcher)
    foreground   the pearl, its highlight and the "T"
    monochrome   the "T" alone

Each layer is a vector drawable on the 108x108 dp adaptive-icon canvas.
Launchers show the middle 72 dp and may crop to a 66 dp circle, so the
pearl (60 dp across) stays inside every mask. minSdk is 31, so no PNG
fallbacks are needed: every device reads mipmap-anydpi-v26/.

Run from the repository root, then commit the output:

    /usr/bin/python3 tools/gen_android_icon.py

Standard library only. The output is plain text and deterministic: two
runs give identical bytes.
"""

from pathlib import Path

RES = Path("android/app/src/main/res")

# tt2.svg, in its 256x256 viewBox.
PEARL_CX, PEARL_CY, PEARL_R = 128, 132, 84
BAR = (84, 86, 88, 22, 6)       # x, y, width, height, corner radius
STEM = (117, 86, 22, 94, 6)
SHINE = (100, 92, 26, 14)       # ellipse cx, cy, rx, ry; opacity 0.55
TILE_TOP, TILE_BOTTOM = "#2f7be6", "#0b2f8a"
PEARL_STOPS = [(0, "#ffffff"), (0.55, "#e8ebf3"), (1, "#a9b1c4")]
PEARL_GRADIENT = (0.38, 0.32, 0.75)   # radialGradient cx, cy, r (objectBoundingBox)
LETTER = "#1240b0"

CANVAS = 108
SCALE = 30 / PEARL_R                  # the pearl becomes 60 dp across


def num(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def pos(x, y):
    """A tt2.svg point on the icon canvas, the pearl centred."""
    return CANVAS / 2 + (x - PEARL_CX) * SCALE, CANVAS / 2 + (y - PEARL_CY) * SCALE


def rounded_rect(rect):
    x, y, w, h, r = rect
    x, y = pos(x, y)
    w, h, r = w * SCALE, h * SCALE, r * SCALE
    return (f"M{num(x + r)},{num(y)} H{num(x + w - r)} A{num(r)},{num(r)} 0 0 1 {num(x + w)},{num(y + r)} "
            f"V{num(y + h - r)} A{num(r)},{num(r)} 0 0 1 {num(x + w - r)},{num(y + h)} "
            f"H{num(x + r)} A{num(r)},{num(r)} 0 0 1 {num(x)},{num(y + h - r)} "
            f"V{num(y + r)} A{num(r)},{num(r)} 0 0 1 {num(x + r)},{num(y)} Z")


def ellipse(cx, cy, rx, ry):
    return (f"M{num(cx - rx)},{num(cy)} A{num(rx)},{num(ry)} 0 1 0 {num(cx + rx)},{num(cy)} "
            f"A{num(rx)},{num(ry)} 0 1 0 {num(cx - rx)},{num(cy)} Z")


def color(hex6, alpha=1.0):
    return f"#{round(alpha * 255):02X}{hex6[1:].upper()}"


def vector(comment, body):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- Generated by tools/gen_android_icon.py from packaging/linux/tt2.svg: {comment}\n"
            f"     Do not edit; change the script and run it again. -->\n"
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{CANVAS}dp"\n    android:height="{CANVAS}dp"\n'
            f'    android:viewportWidth="{CANVAS}"\n    android:viewportHeight="{CANVAS}">\n'
            f"{body}</vector>\n")


def solid(path, fill, alpha=None):
    a = f'\n        android:fillAlpha="{num(alpha)}"' if alpha is not None else ""
    return f'    <path\n        android:pathData="{path}"\n        android:fillColor="{fill}"{a} />\n'


def gradient(path, attrs, stops):
    items = "".join(f'                <item android:offset="{num(o)}" android:color="{color(c)}" />\n'
                    for o, c in stops)
    return (f'    <path android:pathData="{path}">\n'
            f'        <aapt:attr name="android:fillColor">\n'
            f"            <gradient\n{attrs}>\n{items}            </gradient>\n"
            f"        </aapt:attr>\n    </path>\n")


def letter(fill):
    return solid(rounded_rect(BAR), fill) + solid(rounded_rect(STEM), fill)


def background():
    attrs = (f'                android:type="linear"\n'
             f'                android:startX="{num(CANVAS / 2)}" android:startY="0"\n'
             f'                android:endX="{num(CANVAS / 2)}" android:endY="{CANVAS}"')
    return vector("the tile's blue gradient.",
                  gradient(f"M0,0 H{CANVAS} V{CANVAS} H0 Z", attrs, [(0, TILE_TOP), (1, TILE_BOTTOM)]))


def foreground():
    cx, cy = pos(PEARL_CX, PEARL_CY)
    r = PEARL_R * SCALE
    gx, gy, gr = PEARL_GRADIENT   # fractions of the pearl's bounding box (2r square)
    attrs = (f'                android:type="radial"\n'
             f'                android:centerX="{num(cx - r + gx * 2 * r)}"\n'
             f'                android:centerY="{num(cy - r + gy * 2 * r)}"\n'
             f'                android:gradientRadius="{num(gr * 2 * r)}"')
    sx, sy = pos(SHINE[0], SHINE[1])
    body = (gradient(ellipse(cx, cy, r, r), attrs, PEARL_STOPS) + letter(color(LETTER)) +
            solid(ellipse(sx, sy, SHINE[2] * SCALE, SHINE[3] * SCALE), color("#ffffff"), 0.55))
    return vector("the pearl and its \"T\".", body)


def monochrome():
    return vector("the \"T\" alone, tinted by Android 13+ themed icons.", letter("#FFFFFFFF"))


ADAPTIVE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/gen_android_icon.py. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def main():
    outputs = {
        RES / "drawable" / "ic_launcher_background.xml": background(),
        RES / "drawable" / "ic_launcher_foreground.xml": foreground(),
        RES / "drawable" / "ic_launcher_monochrome.xml": monochrome(),
        RES / "mipmap-anydpi-v26" / "ic_launcher.xml": ADAPTIVE,
    }
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))   # LF on every platform
        print(path)


if __name__ == "__main__":
    main()
